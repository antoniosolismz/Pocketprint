#!/usr/bin/env python3
"""Regenerate web/vendor/code128-table.js from python-barcode.

    python3 tools/make-code128-table.py

Why this exists: Code 128 needs 106 eleven-module patterns, and transcribing them by hand is
how you ship a barcode that looks fine and scans as garbage. They are pulled from
python-barcode's implementation of ISO/IEC 15417 instead, then spot-checked against the
published values in the test suite (value 0 = 11011001100, STOP + '11' = 1100011101011).

The output is a classic script for the browser AND a CommonJS module for the tests. Note the
explicit `var CODE128_TABLE` in the browser branch: a top-level `const` in a classic script
lives in the global lexical scope but is NOT a property of window, so `window.CODE128_CODES`
would be undefined. That cost a debugging round.
"""
from __future__ import annotations

from pathlib import Path

TARGET = Path(__file__).resolve().parent.parent / "web" / "vendor" / "code128-table.js"

HEADER = """// Code 128 symbol patterns (ISO/IEC 15417): 106 values, 11 modules each.
//
// Generated by tools/make-code128-table.py from python-barcode's implementation of the
// standard — not transcribed by hand. Spot-checked in web/tests/codes.mjs against the
// published values: value 0 = 11011001100, value 105 = 11010011100, STOP + '11' =
// 1100011101011.
//
// Do not edit by hand; re-run the generator.
"""


def main() -> None:
    from barcode.charsets import code128 as c

    if len(c.CODES) != 106:
        raise SystemExit(f"expected 106 patterns, got {len(c.CODES)}")
    for i, pat in enumerate(c.CODES):
        if len(pat) != 11 or set(pat) - {"0", "1"}:
            raise SystemExit(f"pattern {i} is malformed: {pat!r}")
    assert c.CODES[0] == "11011001100"
    assert (c.STOP + "11") == "1100011101011"

    lines = [HEADER]
    lines.append("const CODE128_CODES = [")
    lines += [f"  '{pat}',  // {i}" for i, pat in enumerate(c.CODES)]
    lines.append("];\n")
    lines.append(f"const CODE128_STOP = '{c.STOP}';")
    lines.append(
        "const CODE128_START = { A: %d, B: %d, C: %d };\n"
        % (c.START_CODES["A"], c.START_CODES["B"], c.START_CODES["C"])
    )
    lines.append("""if (typeof module !== 'undefined' && module.exports) {
  module.exports = { CODE128_CODES, CODE128_STOP, CODE128_START };
} else {
  /* browser: top-level const is not a window property, so export it explicitly */
  var CODE128_TABLE = { CODE128_CODES, CODE128_STOP, CODE128_START };
}""")
    TARGET.write_text("\n".join(lines) + "\n")
    print(f"wrote {TARGET.relative_to(TARGET.parent.parent.parent)} "
          f"({len(c.CODES)} patterns, {TARGET.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
